// dplaax.tlog.v1 is the read surface for per-loop emission transparency
// logs: after every successful publish, a producing loop appends
// {credentialHash, sequenceNo} to its hash-chained log. This service serves
// signed checkpoints and record ranges so a relying party can reconcile
// what it RECEIVED against what the loop EMITTED — at-most-once transport
// loss becomes detectable and the lost events nameable.
//
// Reconciliation scope (declared, not assumed): this proves DIRECT envelope
// delivery per producing loop. Across an aggregate boundary, "did every
// source reading make it into the aggregate?" is a different question,
// answered by joining this log with dplaax.audit.v1.GetConsumedSources.
//
// Trust model (hash-chain PoC posture): the chain hash makes retroactive
// mutation detectable GIVEN an honest earlier checkpoint; the signature
// makes the operator non-repudiably committed to a head. Merkle inclusion
// proofs are the production extension; a future proof RPC is additive.

