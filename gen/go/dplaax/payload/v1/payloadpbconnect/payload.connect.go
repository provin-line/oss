// dplaax.payload.v1 is the publisher's serving boundary for by-reference
// payload delivery: it serves back, by content address, the payload bytes a
// producing process emitted. A subscriber that agreed to by-reference delivery
// dereferences the nil envelope payload against this service.
//
// Charter split from dplaax.vc.v1: that service serves provenance VCs; this one
// serves the DATA a process transformed — bytes that may be confidential (AI
// corpora, supply-chain records) and whose authorization is a distinct resource
// class ("payload" vs "vc"). Adding a payload RPC to VCResolverService would
// conflate the two.
//
// Internet-facing (L2): every request carries an AuthProof verified in-band via
// the wireauth library — the same pattern as dplaax.chain.v1.ChainPeerService,
// and it reuses that package's frozen AuthProof type (a redefinition would be a
// drift source). It carries NO o3co.authz.v1 L1 policy option; the absence is a
// tested descriptor contract mirroring the chain.v1 split.

