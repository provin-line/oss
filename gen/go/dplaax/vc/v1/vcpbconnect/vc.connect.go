// dplaax.vc.v1 is the provenance-chain VC resolver: pipeline runtimes submit
// Verifiable Credentials, which are stored by content address and served back
// for audit and for cross-registry chain resolution.
//
// Message-shape principle (mirrors dplaax.did.v1 / dplaax.schema.v1): a VC
