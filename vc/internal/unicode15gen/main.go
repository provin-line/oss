// Command unicode15gen writes vc's tables of the Unicode 15.0 character
// classes credential.claim.charset refuses (Cc, Cf, White_Space), from the
// Unicode Character Database 15.0.0 itself, so vc judges a claim the same
// whatever Unicode version the Go toolchain's unicode package carries.
//
// It downloads UnicodeData.txt and PropList.txt of UCD 15.0.0, refuses them
// unless their SHA-256 is the one pinned here, and writes the tables:
//
//	go generate ./vc
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

const ucdBase = "https://www.unicode.org/Public/15.0.0/ucd/"

// pinned is the SHA-256 of each UCD 15.0.0 file read.
var pinned = map[string]string{
	"UnicodeData.txt": "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73",
	"PropList.txt":    "e05c0a2811d113dae4abd832884199a3ea8d187ee1b872d8240a788a96540bfd",
}

func main() {
	out := flag.String("o", "charset_unicode15.go", "the Go file to write")
	flag.Parse()
	data := fetch("UnicodeData.txt")
	props := fetch("PropList.txt")
	cc, err := category(bytes.NewReader(data), "Cc")
	if err != nil {
		log.Fatal(err)
	}
	cf, err := category(bytes.NewReader(data), "Cf")
	if err != nil {
		log.Fatal(err)
	}
	ws, err := property(bytes.NewReader(props), "White_Space")
	if err != nil {
		log.Fatal(err)
	}
	for name, rs := range map[string][]rng{"Cc": cc, "Cf": cf, "White_Space": ws} {
		if len(rs) == 0 {
			log.Fatalf("%s: no code points read", name)
		}
	}
	var b strings.Builder
	b.WriteString("// Code generated by vc/internal/unicode15gen from UCD 15.0.0; DO NOT EDIT.\n\n")
	b.WriteString("package vc\n\nimport \"unicode\"\n\n")
	b.WriteString("// The Unicode 15.0 classes credential.claim.charset refuses, pinned here so\n")
	b.WriteString("// the judgment does not follow the toolchain's unicode tables.\n\n")
	b.WriteString(table("unicode15Cc", cc))
	b.WriteString(table("unicode15Cf", cf))
	b.WriteString(table("unicode15WhiteSpace", ws))
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	tmp := *out + ".tmp"
	if err := os.WriteFile(tmp, src, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.Rename(tmp, *out); err != nil {
		log.Fatal(err)
	}
}

// fetch downloads a UCD 15.0.0 file and refuses it unless its SHA-256 is the
// pinned one.
func fetch(name string) []byte {
	client := &http.Client{Timeout: time.Minute}
	resp, err := client.Get(ucdBase + name)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", name, resp.Status)
	}
	b, err := io.ReadAll(io.LimitReader(resp.Body, 8<<20))
	if err != nil {
		log.Fatal(err)
	}
	if err := verify(name, b); err != nil {
		log.Fatal(err)
	}
	return b
}

// verify refuses b unless it is the UCD 15.0.0 file name, by its pinned
// SHA-256.
func verify(name string, b []byte) error {
	want, ok := pinned[name]
	if !ok {
		return fmt.Errorf("%s: no SHA-256 pinned", name)
	}
	sum := sha256.Sum256(b)
	if got := hex.EncodeToString(sum[:]); got != want {
		return fmt.Errorf("%s: SHA-256 %s, want %s", name, got, want)
	}
	return nil
}

// rng is an inclusive range of code points.
type rng struct{ lo, hi rune }

// category reads UnicodeData.txt and returns the code points of general
// category cat, as ranges. A "<…, First>" line and the "<…, Last>" line right
// after it, of the same category, name a range; any other use of them is an
// error.
func category(r io.Reader, cat string) ([]rng, error) {
	var cps []rune
	var first rune = -1
	var firstCat string
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		f := strings.Split(sc.Text(), ";")
		if len(f) < 3 {
			continue
		}
		cp, err := strconv.ParseUint(f[0], 16, 32)
		if err != nil {
			return nil, fmt.Errorf("UnicodeData: %q: %v", f[0], err)
		}
		switch {
		case first >= 0 && !strings.HasSuffix(f[1], ", Last>"):
			return nil, fmt.Errorf("UnicodeData: %s follows a First line, not its Last", f[0])
		case strings.HasSuffix(f[1], ", First>"):
			first, firstCat = rune(cp), f[2]
			continue
		case strings.HasSuffix(f[1], ", Last>"):
			if first < 0 || f[2] != firstCat || rune(cp) < first {
				return nil, fmt.Errorf("UnicodeData: %s is a Last line without its First", f[0])
			}
			if f[2] == cat {
				for c := first; c <= rune(cp); c++ {
					cps = append(cps, c)
				}
			}
			first = -1
			continue
		}
		if f[2] == cat {
			cps = append(cps, rune(cp))
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if first >= 0 {
		return nil, errors.New("UnicodeData: a First line without its Last")
	}
	return ranges(cps), nil
}

// property reads PropList.txt and returns the code points with property
// prop, as ranges.
func property(r io.Reader, prop string) ([]rng, error) {
	var cps []rune
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		cpField, name, ok := strings.Cut(line, ";")
		if !ok || strings.TrimSpace(name) != prop {
			continue
		}
		lo, hi, isRange := strings.Cut(strings.TrimSpace(cpField), "..")
		a, err := strconv.ParseUint(lo, 16, 32)
		if err != nil {
			return nil, fmt.Errorf("PropList: %q: %v", lo, err)
		}
		b := a
		if isRange {
			if b, err = strconv.ParseUint(hi, 16, 32); err != nil {
				return nil, fmt.Errorf("PropList: %q: %v", hi, err)
			}
		}
		for c := rune(a); c <= rune(b); c++ {
			cps = append(cps, c)
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	return ranges(cps), nil
}

// ranges merges code points into sorted, maximal ranges.
func ranges(cps []rune) []rng {
	sort.Slice(cps, func(i, j int) bool { return cps[i] < cps[j] })
	var out []rng
	for _, c := range cps {
		if n := len(out); n > 0 && c <= out[n-1].hi+1 {
			if c > out[n-1].hi {
				out[n-1].hi = c
			}
			continue
		}
		out = append(out, rng{c, c})
	}
	return out
}

// table returns the Go declaration of a unicode.RangeTable named name holding
// rs: 16-bit ranges, then 32-bit ones, and LatinOffset the number of 16-bit
// ranges within Latin-1.
func table(name string, rs []rng) string {
	var r16, r32 strings.Builder
	latin := 0
	for _, r := range rs {
		switch {
		case r.hi <= 0xFFFF:
			fmt.Fprintf(&r16, "\t\t{Lo: 0x%04x, Hi: 0x%04x, Stride: 1},\n", r.lo, r.hi)
			if r.hi <= 0xFF {
				latin++
			}
		case r.lo > 0xFFFF:
			fmt.Fprintf(&r32, "\t\t{Lo: 0x%x, Hi: 0x%x, Stride: 1},\n", r.lo, r.hi)
		default:
			fmt.Fprintf(&r16, "\t\t{Lo: 0x%04x, Hi: 0xffff, Stride: 1},\n", r.lo)
			fmt.Fprintf(&r32, "\t\t{Lo: 0x10000, Hi: 0x%x, Stride: 1},\n", r.hi)
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "var %s = &unicode.RangeTable{\n", name)
	if r16.Len() > 0 {
		fmt.Fprintf(&b, "\tR16: []unicode.Range16{\n%s\t},\n", r16.String())
	}
	if r32.Len() > 0 {
		fmt.Fprintf(&b, "\tR32: []unicode.Range32{\n%s\t},\n", r32.String())
	}
	fmt.Fprintf(&b, "\tLatinOffset: %d,\n}\n\n", latin)
	return b.String()
}
